function chilli(
  slug: string,
  name: string,
  hindi: string,
  region: string,
  heat: HeatLevel,
  aliases: string[],
  extra?: Partial<SpiceEntity>
): SpiceEntity {
  return spice({
    id: slug,
    slug,
    canonicalName: name,
    commonNames: [name, `${name} chilli`],
    indianNames: [name],
    hindiName: hindi,
    regionalNames: [region],
    botanicalName: extra?.botanicalName ?? "Capsicum annuum",
    botanicalFamily: "Solanaceae",
    shortDescription: extra?.shortDescription ?? `${name} is an Indian chilli variety used whole, flaked, or as powder.`,
    description:
      extra?.description ??
      `${name} is a recognised Indian chilli type associated with ${region}. Heat, colour, and skin thickness vary by variety. Forms include whole pods, flakes, crushed chilli, and powder.`,
    growingRegions: [region],
    flavourProfile: extra?.flavourProfile ?? "Chilli heat with variety-specific fruitiness",
    aromaProfile: extra?.aromaProfile ?? "Dried red chilli aroma",
    colour: extra?.colour ?? "Red when dried",
    heatLevel: heat,
    culinaryUses: ["Curry", "Pickle", "Masala", "Tandoori"],
    category: "indian-chillies",
    relatedSlugs: extra?.relatedSlugs ?? ["kashmiri-chilli", "byadgi-chilli", "guntur-sannam"],
    recipeSlugs: ["curry", "pickle"],
    aliases,
    forms: CHILLI,
    varieties: [{ slug, name: `${name}`, region }],
    grades: ["premium", "standard", "export"],
    featured: extra?.featured,
    needsVerification: extra?.needsVerification,
  });
}

