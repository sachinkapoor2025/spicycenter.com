function simpleSpice(opts: {
  id: string;
  name: string;
  hindi: string;
  botanical: string;
  family: string;
  category: string;
  regions: string[];
  flavour: string;
  aroma: string;
  colour: string;
  heat?: HeatLevel;
  forms?: SpiceForm[];
  aliases: string[];
  related: string[];
  uses: string[];
  featured?: boolean;
  varieties?: SpiceEntity["varieties"];
  grades?: string[];
  sanskrit?: string;
  needsVerification?: boolean;
}): SpiceEntity {
  return spice({
    id: opts.id,
    slug: opts.id,
    canonicalName: opts.name,
    commonNames: [opts.name],
    indianNames: [opts.name],
    hindiName: opts.hindi,
    regionalNames: opts.regions,
    sanskritName: opts.sanskrit,
    botanicalName: opts.botanical,
    botanicalFamily: opts.family,
    shortDescription: `${opts.name} — Indian spice used in ${opts.uses.slice(0, 3).join(", ").toLowerCase()}.`,
    description: `${opts.name} (${opts.botanical}) is used in Indian cooking. Growing regions associated with Indian supply include ${opts.regions.join(", ")}. Product pages list form, grade, and food information separately from this botanical profile.`,
    growingRegions: opts.regions,
    flavourProfile: opts.flavour,
    aromaProfile: opts.aroma,
    colour: opts.colour,
    heatLevel: opts.heat ?? "none",
    culinaryUses: opts.uses,
    category: opts.category,
    relatedSlugs: opts.related,
    recipeSlugs: ["curry"],
    aliases: opts.aliases,
    forms: opts.forms ?? WP,
    varieties: opts.varieties ?? [{ slug: opts.id, name: opts.name }],
    grades: opts.grades ?? ["premium", "standard", "export"],
    featured: opts.featured,
    needsVerification: opts.needsVerification,
  });
}

