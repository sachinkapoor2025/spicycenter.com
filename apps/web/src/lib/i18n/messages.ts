function restoreWhitespace(original: string, translated: string): string {
  const lead = original.match(/^\s*/)?.[0] ?? "";
  const trail = original.match(/\s*$/)?.[0] ?? "";
  return `${lead}${translated}${trail}`;
}

export function canonicalEnglish(phrase: string): string {
  const trimmed = phrase.trim();
  if (!trimmed) return phrase;
  for (const table of Object.values(MESSAGES)) {
    if (table[trimmed]) return restoreWhitespace(phrase, trimmed);
    for (const [en, translated] of Object.entries(table)) {
      if (translated === trimmed) return restoreWhitespace(phrase, en);
    }
  }
  return phrase;
}

export function translatePhrase(locale: StorefrontLocale, phrase: string): string {
  const trimmed = phrase.trim();
  if (!trimmed || locale === "en") return phrase;
  const table = MESSAGES[locale];
  if (!table) return phrase;
  const direct = table[trimmed];
  if (direct) return restoreWhitespace(phrase, direct);
  const alias = EXTRA_ALIASES[trimmed];
  if (alias && table[alias]) return restoreWhitespace(phrase, table[alias]);
  return phrase;
}
